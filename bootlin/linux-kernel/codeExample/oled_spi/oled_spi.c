static int oled_probe(struct spi_device *spi){
	pr_info("%s\n", __func__);
	int ret;
	u8 buff[8];
	struct oled_device *oled_dev;
	oled_dev = devm_kzalloc(&spi->dev, sizeof(*oled_dev), GFP_KERNEL);
	if(!oled_dev) {
		pr_info("%s cannot alloc oled_dev\n", __func__);
		return -ENOMEM;
	}
	oled_dev->oled_dev = spi;
	
	oled_dev->reset_gpio = devm_gpiod_get(&spi->dev, "reset", GPIOD_OUT_LOW);
	if (IS_ERR(oled_dev->reset_gpio)) {
		pr_info("%s cannot get reset gpios\n", __func__);
		return PTR_ERR(oled_dev->reset_gpio);
	}
	oled_dev->dc_gpio = devm_gpiod_get(&spi->dev, "dc", GPIOD_OUT_LOW);
	if (IS_ERR(oled_dev->dc_gpio)) {
		pr_info("%s cannot get dc gpios\n", __func__);
		return PTR_ERR(oled_dev->dc_gpio);
	}
	gpiod_set_value(oled_dev->reset_gpio, 0);
	msleep(100);
	gpiod_set_value(oled_dev->reset_gpio, 1);
	msleep(100);

	gpiod_set_value(oled_dev->dc_gpio, 0);

	uint8_t init_cmds[] = {
		0xAE, // Display OFF (Sleep mode)
		0xD5, 0x80, // Set Display Clock Divide Ratio
		0xA8, 0x3F, // Set Multiplex Ratio (64 lines)
		0xD3, 0x00, // Set Display Offset
		0x40, // Set Display Start Line
		0x8D, 0x14, // CHÚ Ý: Bật Charge Pump (0x14 là Enable, thiếu lệnh này màn hình không lên hình)
		0xA1, // Set Segment Re-map
		0xC8, // Set COM Output Scan Direction
		0xDA, 0x12, // Set COM Pins Hardware Configuration
		0x81, 0x7F, // Set Contrast Control
		0xD9, 0xF1, // Set Pre-charge Period
		0xDB, 0x40, // Set VCOMH Deselect Level
		0x20, 0x00, // Set Memory Addressing Mode = Horizontal
		0xA4, // Output follows RAM content (Hoặc 0xA5 tùy bạn thử nghiệm)
		0xA6, // Set Normal Display
		0xAF  // DISPLAY ON (Lệnh chính thức để bật màn hình)
	};
	ret = spi_write(spi, init_cmds, sizeof(init_cmds));
	pr_info("ret %d\n", ret);

	oled_puts(oled_dev, 2, 0, "Hello World!");
	
	return 0;
}
