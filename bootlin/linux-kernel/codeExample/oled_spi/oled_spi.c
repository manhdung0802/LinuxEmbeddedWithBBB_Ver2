struct oled_device {
	struct spi_device *oled_dev;
	struct gpio_desc *reset_gpio;
	struct gpio_desc *dc_gpio;
};
void oled_putc(struct oled_device *oled, u8 page, u8 col, char c)
{
    // Giới hạn ký tự thuộc bảng mã in được
    if (c < 32 || c > 126)
        c = ' ';

    // 1. Đặt vị trí con trỏ màn hình
    gpiod_set_value(oled->dc_gpio, 0); // Command
    
    u8 set_pos_cmds[] = {
        0x21, col, col + 7,   // Phạm vi Cột từ col -> col + 7 (rộng 8px)
        0x22, page, page      // Phạm vi Page tại page hiện tại (cao 8px)
    };
    spi_write(oled->oled_dev, set_pos_cmds, sizeof(set_pos_cmds));

    // 2. Gửi 8 byte điểm ảnh của ký tự đó -> Data
    gpiod_set_value(oled->dc_gpio, 1); // Data
    
    // Lấy mảng 8 byte tương ứng với ký tự 'c'
    const u8 *char_pixels = font8x8[c]; 
    spi_write(oled->oled_dev, char_pixels, 8);
}
void oled_puts(struct oled_device *oled, u8 page, u8 col, const char *str)
{
    while (*str) {
        // Vẽ ký tự hiện tại
        oled_putc(oled, page, col, *str);
        
        // Nhảy sang cột tiếp theo (phông 8px + 0px khoảng cách = 8px)
        col += 8; 
        
        // Nếu chạm mép phải màn hình (128px), tự động xuống dòng (Page tiếp theo)
        if (col > 120) {
            col = 0;
            page++;
            if (page > 7) page = 0; // Tràn màn hình thì quay lại Page 0
        }

        str++; // Chuyển sang ký tự tiếp theo trong chuỗi
    }
}

